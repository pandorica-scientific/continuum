/**
 * Write `drizzle/0000_baseline.sql` from the Drizzle schema.
 *
 * The schema has two halves. drizzle-kit writes the first — tables, columns,
 * indexes, foreign keys — and cannot write the second: triggers, generated
 * columns, CHECK constraints, expression indexes, the net-worth view, and the
 * seed rows a foreign key needs to be satisfiable. That second half used to be
 * appended to the migration by hand, which made the schema two sources of truth
 * that nothing reconciled. It now lives beside the tables it constrains, in
 * `src/lib/server/db/schema/*.ts`, and this script puts the two halves together.
 *
 * `drizzle/0000_baseline.sql` is therefore a BUILD ARTEFACT. Nothing edits it by
 * hand, `tests/unit/baseline-composition.test.ts` fails if the committed file
 * and the schema modules disagree, and a change to either half is made in
 * TypeScript and re-composed with `npm run db:baseline`.
 *
 * ONE FILE, rewritten in place, rather than a chain of migrations. That is a
 * deliberate choice recorded in ARCHITECTURE.md, and it is what makes the
 * composed output safe to regenerate: there is no history to preserve.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const OUT_SQL = join(ROOT, 'drizzle', '0000_baseline.sql');
const OUT_META = join(ROOT, 'drizzle', 'meta');
const SCHEMA = './src/lib/server/db/schema/index.ts';

/**
 * Run drizzle-kit against a throwaway output directory.
 *
 * Its own config points `out` at `drizzle/`, where a baseline already exists, so
 * generating there would emit `0001_*.sql` and start the chain this project does
 * not keep. A temporary directory gets the complete DDL for the current schema
 * every time instead of a diff against the last one.
 *
 * The URL is a placeholder: `generate` reads the schema and the previous
 * snapshot, and never opens a connection. The config has to live inside the
 * project, because drizzle-kit resolves its own import from the config's
 * location.
 */
function generateTables(outDir) {
	const configDir = join(ROOT, 'drizzle', '.compose');
	const configPath = join(configDir, 'config.ts');
	mkdirSync(configDir, { recursive: true });
	writeFileSync(
		configPath,
		`import { defineConfig } from 'drizzle-kit';\n` +
			`export default defineConfig({\n` +
			`\tschema: '${SCHEMA}',\n` +
			`\tout: ${JSON.stringify(outDir)},\n` +
			`\tdialect: 'postgresql',\n` +
			`\tdbCredentials: { url: 'postgres://compose:compose@127.0.0.1:1/compose' },\n` +
			`\tbreakpoints: true\n` +
			`});\n`
	);
	try {
		execFileSync('npx', ['drizzle-kit', 'generate', `--config=${configPath}`, '--name=baseline'], {
			cwd: ROOT,
			stdio: ['ignore', 'ignore', 'inherit']
		});
	} finally {
		rmSync(configDir, { recursive: true, force: true });
	}
	return readFileSync(join(outDir, '0000_baseline.sql'), 'utf8');
}

/**
 * Read the appendix out of the schema modules.
 *
 * Bundled first, because Node cannot import the schema files directly: they use
 * extensionless relative specifiers, which is what drizzle-kit and Vite expect
 * and what Node's own TypeScript loader refuses.
 */
async function readSections() {
	const esbuild = await import('esbuild');
	const built = await esbuild.build({
		entryPoints: [join(ROOT, 'src/lib/server/db/schema/baseline.ts')],
		bundle: true,
		format: 'esm',
		platform: 'node',
		write: false,
		external: ['drizzle-orm']
	});
	// Inside the project, not in a temp directory: `drizzle-orm` is left external
	// so the bundle stays small, and a module outside the tree cannot resolve it.
	const dir = join(ROOT, 'drizzle', '.compose');
	const file = join(dir, 'baseline.mjs');
	mkdirSync(dir, { recursive: true });
	writeFileSync(file, built.outputFiles[0].text);
	try {
		return (await import(pathToFileURL(file).href)).BASELINE_SECTIONS;
	} finally {
		rmSync(dir, { recursive: true, force: true });
	}
}

const HEADER = `-- GENERATED FILE — DO NOT EDIT.
--
-- Written by \`npm run db:baseline\` from the Drizzle schema in
-- src/lib/server/db/schema/. Everything above the appendix below is drizzle-kit's
-- output; everything in the appendix is exported from those same modules,
-- because drizzle-kit models tables, columns, indexes and foreign keys and
-- nothing else.
--
-- Change the schema in TypeScript and re-run the script. Editing this file by
-- hand puts it out of step with the modules, and
-- tests/unit/baseline-composition.test.ts fails when that happens.
`;

const RULE = '-- ' + '='.repeat(73);

const APPENDIX_HEADER = `${RULE}
-- Everything below this line cannot be generated by drizzle-kit: triggers,
-- generated columns, CHECK constraints, expression indexes, the net-worth view,
-- and the seed rows a foreign key needs to be satisfiable.
--
-- So \`db:generate\` alone cannot notice any of it going missing, and a database
-- built with \`drizzle-kit push\` would have the tables without the integrity they
-- depend on. Build the schema with migrations.
--
-- Each block is exported from the schema module that owns the tables it
-- constrains; the two lists that were once repeated here — the enum CHECK
-- constraints and the entity kinds — are generated from src/lib/enums.ts.
${RULE}`;

const outDir = mkdtempSync(join(tmpdir(), 'continuum-drizzle-'));
try {
	const tables = generateTables(outDir).trim();
	const sections = await readSections();

	const appendix = sections
		.map(({ title, sql }) => `-- ---- ${title} ----\n${sql.trim()}`)
		.join('\n--> statement-breakpoint\n\n');

	const composed = `${HEADER}\n${tables}\n--> statement-breakpoint\n\n${APPENDIX_HEADER}\n\n${appendix}\n`;
	writeFileSync(OUT_SQL, composed);

	// The snapshot is drizzle-kit's own record of the schema and has to travel
	// with the file it describes. The journal's timestamp is kept from whatever
	// is already committed, so re-composing an unchanged schema is a no-op in
	// git rather than a one-line diff every time.
	mkdirSync(OUT_META, { recursive: true });
	writeFileSync(
		join(OUT_META, '0000_snapshot.json'),
		readFileSync(join(outDir, 'meta', '0000_snapshot.json'), 'utf8')
	);
	let journal = readFileSync(join(outDir, 'meta', '_journal.json'), 'utf8');
	try {
		const existing = JSON.parse(readFileSync(join(OUT_META, '_journal.json'), 'utf8'));
		const fresh = JSON.parse(journal);
		fresh.entries[0].when = existing.entries[0].when;
		journal = `${JSON.stringify(fresh, null, 2)}\n`;
	} catch {
		// No journal yet: keep the one drizzle-kit just wrote.
	}
	writeFileSync(join(OUT_META, '_journal.json'), journal);

	process.stdout.write(
		`${basename(OUT_SQL)}: ${composed.split('\n').length} lines, ${sections.length} appendix sections\n`
	);
} finally {
	rmSync(outDir, { recursive: true, force: true });
}
